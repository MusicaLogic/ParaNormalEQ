#pragma once

#include <JuceHeader.h>
#include <array>

//==============================================================================
// Filter role
//==============================================================================

enum class EQBandType
{
    lowPass,
    lowShelf,

    bell,

    highPass,
    highShelf
};


//==============================================================================
// Position in the three-band EQ
//==============================================================================

enum class EQBandRole
{
    left,
    middle,
    right
};


//==============================================================================
// One parametric EQ section
//==============================================================================

struct EQBand
{
    EQBandRole role = EQBandRole::middle;
    EQBandType type = EQBandType::bell;

    float frequency = 1000.0f;
    float gain      = 0.0f;
    float q         = 0.707f;

    bool enabled = true;
};
